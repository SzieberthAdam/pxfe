#define DIR "testdata/outline/"

static unsigned char *slurp(const char *path, size_t *n) {
    FILE *fp = fopen(path, "rb");
    unsigned char *b;
    long sz;
    if (!fp) return NULL;
    fseek(fp, 0, SEEK_END); sz = ftell(fp); fseek(fp, 0, SEEK_SET);
    b = (unsigned char *)malloc((size_t)sz + 1);
    if (b && fread(b, 1, (size_t)sz, fp) != (size_t)sz) { free(b); b = NULL; }
    fclose(fp);
    if (n) *n = (size_t)sz;
    return b;
}

static double ink(const OutlineBitmap *b) {
    double s = 0;
    long i, n = (long)b->w * b->h;
    for (i = 0; i < n; i++) s += b->pix[i];
    return s / 255.0;
}

static Outline *open_ok(const char *file, char *err) {
    char path[256];
    snprintf(path, sizeof path, DIR "%s", file);
    return outline_open(path, err, 256);
}

