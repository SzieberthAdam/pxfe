typedef struct { const char *file, *fmt; int noto; } FontInfo;
static const FontInfo FONTS[] = {
    {"NotoSub.ttf", "ttf", 1}, {"NotoSub.woff", "woff", 1}, {"NotoSub.eot", "eot", 1}, {"NotoSub.xor.eot", "eot", 1},
    {"NotoSub.ttc", "ttc", 1}, {"NotoSubCff.otf", "otf", 1}, {"UnifontSub.otf", "otf", 0}, {"NotoSub.pfb", "pfb", 1},
};
#define NFONTS ((int)(sizeof FONTS / sizeof FONTS[0]))

static void test_each_format(void) {
    int i;
    for (i = 0; i < NFONTS; i++) {
        char err[256] = "", msg[400];
        Outline *f = open_ok(FONTS[i].file, err);
        OutlineBitmap b;
        int g, asc, desc, gap, rc;
        snprintf(msg, sizeof msg, "%s: opens (%s)", FONTS[i].file, err);
        CHECK(f != NULL, msg);
        if (!f) continue;
        snprintf(msg, sizeof msg, "%s: format is %s", FONTS[i].file, FONTS[i].fmt);
        CHECK(strcmp(outline_format(f), FONTS[i].fmt) == 0, msg);
        if (FONTS[i].noto) {
            snprintf(msg, sizeof msg, "%s: family contains Noto Sans (\"%s\")", FONTS[i].file, outline_family(f));
            CHECK(strstr(outline_family(f), "Noto Sans") != NULL, msg);
            snprintf(msg, sizeof msg, "%s: style is Regular (\"%s\")", FONTS[i].file, outline_style(f));
            CHECK(strcmp(outline_style(f), "Regular") == 0, msg);
        } else {
            snprintf(msg, sizeof msg, "%s: family \"%s\" style \"%s\"", FONTS[i].file, outline_family(f), outline_style(f));
            CHECK(outline_family(f)[0] != 0, msg);
        }
        snprintf(msg, sizeof msg, "%s: units per em %d", FONTS[i].file, outline_units_per_em(f));
        CHECK(outline_units_per_em(f) == 1000 || (!FONTS[i].noto && outline_units_per_em(f) >= 16), msg);
        outline_metrics(f, &asc, &desc, &gap);
        snprintf(msg, sizeof msg, "%s: metrics %d/%d/%d plausible", FONTS[i].file, asc, desc, gap);
        CHECK(asc > 0 && desc < 0 && desc > -asc && (!FONTS[i].noto || (asc > 500 && asc < 1500 && desc > -600)), msg);
        g = outline_glyph_index(f, 'A');
        snprintf(msg, sizeof msg, "%s: cmap A -> glyph %d", FONTS[i].file, g);
        CHECK(g > 0 && g < outline_glyph_count(f), msg);
        CHECK(outline_glyph_index(f, 0x4E00) == 0, "  cmap of a missing code point is 0");
        CHECK(outline_glyph_index(f, -5) == 0 && outline_glyph_index(f, 0x110000) == 0, "  cmap of a bad code point is 0");
        CHECK(outline_advance(f, g) > 0, "  advance of A positive");
        rc = outline_rasterize(f, 'A', 100.0f, 0, 0, &b, err, 256);
        snprintf(msg, sizeof msg, "%s: raster A at 100 px ok (%s)", FONTS[i].file, err);
        CHECK(rc == OUTLINE_OK && b.pix, msg);
        if (rc == OUTLINE_OK && b.pix) {
            double a = ink(&b), frac = a / ((double)b.w * b.h);
            snprintf(msg, sizeof msg, "  bbox %dx%d at (%d,%d), ink %.0f (%.2f of box), advance %.1f", b.w, b.h, b.left, b.top, a, frac, b.advance);
            CHECK(b.w >= 30 && b.w <= 160 && b.h >= 40 && b.h <= 200 && b.top > 0 && b.top <= 150 && frac > 0.08 && frac < 0.8 && b.advance > 30 && b.advance < 200, msg);
            if (FONTS[i].noto) {
                CHECK(b.top >= 68 && b.top <= 76 && b.h >= 68 && b.h <= 78, "  Noto cap height about 71 px");
                CHECK(fabsf(b.advance - 63.9f) < 1.0f, "  Noto A advance about 63.9 px");
            }
        }
        outline_bitmap_free(&b);
        outline_close(f);
    }
}

static void test_identical_containers(void) {
    static const char *files[] = {"NotoSub.woff", "NotoSub.eot", "NotoSub.xor.eot"};
    static const int cps[] = {'A', 'g', 0xE9, 'o', '3'};
    char err[256];
    Outline *ref = open_ok("NotoSub.ttf", err);
    int i, k, same = 1, n = 0;
    CHECK(ref != NULL, "container comparison: reference ttf opens");
    for (i = 0; i < 3 && ref; i++) {
        Outline *f = open_ok(files[i], err);
        if (!f) { same = 0; continue; }
        for (k = 0; k < 5; k++) {
            OutlineBitmap a, b;
            int r1 = outline_rasterize(ref, cps[k], 37.5f, 0.3f, 0.6f, &a, err, 256);
            int r2 = outline_rasterize(f, cps[k], 37.5f, 0.3f, 0.6f, &b, err, 256);
            n++;
            if (r1 != OUTLINE_OK || r2 != OUTLINE_OK || a.w != b.w || a.h != b.h || a.left != b.left || a.top != b.top ||
                a.advance != b.advance || (a.w && memcmp(a.pix, b.pix, (size_t)a.w * a.h) != 0)) same = 0;
            outline_bitmap_free(&a); outline_bitmap_free(&b);
        }
        outline_close(f);
    }
    CHECK(same && n == 15, "ttf, woff, eot and xor-eot give identical bitmaps (15 glyph renderings)");
    outline_close(ref);
}

static void test_ttc(void) {
    char err[256] = "";
    Outline *f = open_ok("NotoSub.ttc", err);
    OutlineBitmap a, b;
    CHECK(f != NULL, "ttc opens");
    if (!f) return;
    CHECK(outline_face_count(f) == 2 && outline_face(f) == 0, "ttc has 2 faces, face 0 selected");
    CHECK(strcmp(outline_style(f), "Regular") == 0 && outline_glyph_index(f, 'D') > 0, "face 0: Regular, has D");
    CHECK(outline_rasterize(f, 'A', 100, 0, 0, &a, err, 256) == OUTLINE_OK, "face 0: raster A");
    CHECK(outline_select_face(f, 1, err, 256) == 0 && outline_face(f) == 1, "select face 1");
    CHECK(strcmp(outline_style(f), "Bold") == 0 && strstr(outline_family(f), "Noto Sans") != NULL, "face 1: Bold, Noto Sans");
    CHECK(outline_glyph_index(f, 'D') == 0 && outline_glyph_index(f, 'c') > 0, "face 1 has its own glyph set (no D, has c)");
    CHECK(outline_rasterize(f, 'A', 100, 0, 0, &b, err, 256) == OUTLINE_OK, "face 1: raster A");
    CHECK(ink(&b) > ink(&a) * 1.1, "bold A has more ink than regular A");
    outline_bitmap_free(&a); outline_bitmap_free(&b);
    err[0] = 0;
    CHECK(outline_select_face(f, 2, err, 256) < 0 && err[0] && outline_face(f) == 1, "face 2 fails with a message, face 1 stays");
    CHECK(outline_select_face(f, -1, NULL, 0) < 0, "face -1 fails (no error buffer is fine)");
    CHECK(outline_select_face(f, 0, err, 256) == 0 && outline_glyph_index(f, 'D') > 0, "back to face 0");
    outline_close(f);
    f = open_ok("NotoSub.ttf", err);
    CHECK(f && outline_face_count(f) == 1 && outline_select_face(f, 0, err, 256) == 0 && outline_select_face(f, 1, err, 256) < 0,
          "a plain font has one face");
    outline_close(f);
}

/* ---- comparison with stb_truetype on valid fonts ---- */

static void stb_compare(const char *file, int cp, float px, float fx, const char *label) {
    char err[256], msg[200];
    size_t n;
    unsigned char path_ok = 0;
    char path[256];
    unsigned char *data;
    stbtt_fontinfo info;
    Outline *f;
    OutlineBitmap b;
    snprintf(path, sizeof path, DIR "%s", file);
    data = slurp(path, &n);
    f = outline_open(path, err, 256);
    if (data && f && stbtt_InitFont(&info, data, stbtt_GetFontOffsetForIndex(data, 0))) path_ok = 1;
    snprintf(msg, sizeof msg, "stb %s: font opens in both", label);
    CHECK(path_ok, msg);
    if (path_ok) {
        float scale = px / (float)outline_units_per_em(f);
        int g = stbtt_FindGlyphIndex(&info, cp), w, h, xo, yo;
        unsigned char *sb;
        CHECK(g == outline_glyph_index(f, cp), "  same glyph index as stb");
        sb = stbtt_GetGlyphBitmapSubpixel(&info, scale, scale, fx, 0, g, &w, &h, &xo, &yo);
        CHECK(outline_rasterize(f, cp, px, fx, 0, &b, err, 256) == OUTLINE_OK && sb, "  both rasterise");
        if (sb && b.pix) {
            double si = 0, di = 0, oi = ink(&b);
            long i, cnt = 0;
            int same_box = (abs(b.left - xo) <= 1 && abs(b.top + yo) <= 1 && abs(b.w - w) <= 2 && abs(b.h - h) <= 2);
            for (i = 0; i < (long)w * h; i++) si += sb[i];
            si /= 255.0;
            snprintf(msg, sizeof msg, "  %s: box %dx%d@(%d,%d) vs stb %dx%d@(%d,%d)", label, b.w, b.h, b.left, b.top, w, h, xo, -yo);
            CHECK(same_box, msg);
            snprintf(msg, sizeof msg, "  %s: ink %.1f vs stb %.1f within 1.5%%", label, oi, si);
            CHECK(fabs(oi - si) <= 0.015 * si + 0.5, msg);
            if (b.left == xo && b.top == -yo && b.w == w && b.h == h) {
                for (i = 0; i < (long)w * h; i++) { di += abs((int)b.pix[i] - (int)sb[i]); cnt++; }
                snprintf(msg, sizeof msg, "  %s: mean pixel difference %.2f levels (< 6; stb itself is only approximate)", label, cnt ? di / cnt : 0.0);
                CHECK(cnt && di / cnt < 6.0, msg);
            }
        }
        if (sb) stbtt_FreeBitmap(sb, NULL);
        outline_bitmap_free(&b);
    }
    free(data);
    outline_close(f);
}

static void test_vs_stb(void) {
    stb_compare("NotoSub.ttf", 'A', 100, 0, "ttf A 100px");
    stb_compare("NotoSub.ttf", 'g', 63, 0, "ttf g 63px");
    stb_compare("NotoSub.ttf", 0xE9, 80, 0, "ttf composite eacute 80px");
    stb_compare("NotoSub.ttf", 'o', 40, 0.5f, "ttf o 40px shifted 0.5");
    stb_compare("NotoSub.ttf", 'B', 50, 0, "ttf B 50px");
    stb_compare("NotoSubCff.otf", 'g', 100, 0, "cff g 100px");
    stb_compare("NotoSubCff.otf", 'C', 33, 0, "cff C 33px");
    stb_compare("NotoSubCff.otf", 0xE9, 80, 0, "cff eacute 80px");
    stb_compare("UnifontSub.otf", 'A', 160, 0, "unifont A 160px");
    stb_compare("UnifontSub.otf", 'b', 48, 0, "unifont b 48px");
}

static void test_cff_vs_ttf(void) {
    char err[256];
    Outline *t = open_ok("NotoSub.ttf", err), *c = open_ok("NotoSubCff.otf", err);
    static const int cps[] = {'A', 'g', 'o', 'e', 0xE9, '0'};
    int k, ok = 1;
    if (t && c) {
        for (k = 0; k < 6; k++) {
            OutlineBitmap a, b;
            if (outline_rasterize(t, cps[k], 100, 0, 0, &a, err, 256) != OUTLINE_OK ||
                outline_rasterize(c, cps[k], 100, 0, 0, &b, err, 256) != OUTLINE_OK) { ok = 0; continue; }
            if (fabs(ink(&a) - ink(&b)) > 0.01 * ink(&a) + 2 || abs(a.w - b.w) > 1 || abs(a.h - b.h) > 1 || abs(a.top - b.top) > 1) ok = 0;
            outline_bitmap_free(&a); outline_bitmap_free(&b);
        }
    } else ok = 0;
    CHECK(ok, "CFF redraw of the TrueType subset matches it (box and ink within 1%)");
    outline_close(t); outline_close(c);
}

static void test_pfb(void) {
    char err[256] = "";
    Outline *f = open_ok("NotoSub.pfb", err), *t = open_ok("NotoSub.ttf", err);
    OutlineBitmap a, b;
    int asc, desc, gap, k;
    static const int cps[] = {'A', 'g', 'o', '3', 'H', 0xE9};
    int ok = 1;
    CHECK(f && t, "pfb and ttf open");
    if (!f || !t) { outline_close(f); outline_close(t); return; }
    CHECK(strcmp(outline_family(f), "Noto Sans Sub") == 0 && strcmp(outline_style(f), "Regular") == 0, "pfb family and style from FontInfo");
    outline_metrics(f, &asc, &desc, &gap);
    CHECK(asc == 1000 && desc == -300 && gap == 0, "pfb metrics from FontBBox");
    CHECK(outline_glyph_count(f) > 15, "pfb glyph count");
    CHECK(outline_symbolic(f) == 1 && outline_symbolic(t) == 0, "SYMBOLIC: the pfb's own Encoding (not StandardEncoding) is symbolic, the ttf (no (3,0) cmap) is not");
    CHECK(outline_glyph_index(f, 'A') > 0 && outline_glyph_index(f, 0x25A0) > 0 && outline_glyph_index(f, 0x25A1) > 0, "pfb names: A, uni25A0, u25A1");
    CHECK(outline_glyph_index(f, 0xE9) > 0, "pfb name eacute -> U+00E9");
    CHECK(outline_glyph_index(f, 0x7E) > 0, "pfb Encoding maps code 126 to foo");
    CHECK(outline_glyph_index(f, 0xB4) > 0, "pfb name acute -> U+00B4");
    CHECK(outline_glyph_index(f, 0x20) > 0 && outline_glyph_index(f, 'Z') == 0, "pfb: space present, Z missing");
    CHECK(outline_advance(f, outline_glyph_index(f, 'A')) == outline_advance(t, outline_glyph_index(t, 'A')), "pfb advance of A equals the ttf one");
    for (k = 0; k < 6; k++) {
        if (outline_rasterize(f, cps[k], 100, 0, 0, &a, err, 256) != OUTLINE_OK || outline_rasterize(t, cps[k], 100, 0, 0, &b, err, 256) != OUTLINE_OK) { ok = 0; continue; }
        if (fabs(ink(&a) - ink(&b)) > 0.01 * ink(&b) + 2 || abs(a.w - b.w) > 1 || abs(a.h - b.h) > 1 || abs(a.top - b.top) > 1 || abs(a.left - b.left) > 1) {
            printf("      glyph %d: pfb %dx%d@(%d,%d) ink %.1f, ttf %dx%d@(%d,%d) ink %.1f\n", cps[k], a.w, a.h, a.left, a.top, ink(&a), b.w, b.h, b.left, b.top, ink(&b));
            ok = 0;
        }
        outline_bitmap_free(&a); outline_bitmap_free(&b);
    }
    CHECK(ok, "pfb outlines (incl. seac eacute) match the ttf ones: box and ink within 1%");
    /* hand made glyphs with exactly known areas (units^2 * (px/1000)^2) */
    CHECK(outline_rasterize(f, 0x25A0, 100, 0, 0, &a, err, 256) == OUTLINE_OK && fabs(ink(&a) - 3500.0) < 3.0 && a.w == 50 && a.h == 70 && a.left == 10 && a.top == 70,
          "flex bar (Subrs 0-2 flex, hstem/vstem): 50x70 at (10,70), area 3500");
    outline_bitmap_free(&a);
    CHECK(outline_rasterize(f, 0x25A1, 100, 0, 0, &a, err, 256) == OUTLINE_OK && fabs(ink(&a) - 3500.0) < 3.0, "hint replacement bar: area 3500");
    outline_bitmap_free(&a);
    CHECK(outline_rasterize(f, 0x7E, 100, 0, 0, &a, err, 256) == OUTLINE_OK && fabs(ink(&a) - 1750.0) < 3.0, "triangle foo: area 1750");
    outline_bitmap_free(&a);
    CHECK(outline_advance(f, outline_glyph_index(f, 0x7E)) == 600 && outline_advance(f, outline_glyph_index(f, 0x25A0)) == 700, "hsbw advances 600 and 700");
    CHECK(outline_rasterize(f, 0x20, 50, 0, 0, &a, err, 256) == OUTLINE_OK && a.w == 0 && a.pix == NULL && a.advance > 5, "space: blank bitmap with advance");
    outline_bitmap_free(&a);
    outline_close(f); outline_close(t);
}

static void test_raster_properties(void) {
    char err[256];
    Outline *f = open_ok("NotoSub.ttf", err);
    OutlineBitmap a, b, c, d;
    int l, t, w, h;
    float adv;
    CHECK(f != NULL, "raster properties: font opens");
    if (!f) return;
    CHECK(outline_rasterize(f, 'g', 48, 0, 0, &a, err, 256) == OUTLINE_OK, "g at 48 px");
    CHECK(a.top - a.h < 0 && a.top > 0, "g has a descender: bitmap reaches below the baseline");
    CHECK(outline_glyph_bbox(f, outline_glyph_index(f, 'g'), 48, 0, 0, &l, &t, &w, &h, &adv, err, 256) == OUTLINE_OK &&
          l == a.left && t == a.top && w == a.w && h == a.h && adv == a.advance, "outline_glyph_bbox equals the raster box");
    CHECK(outline_rasterize(f, 'g', 48, 0, 0, &b, err, 256) == OUTLINE_OK && a.w == b.w && memcmp(a.pix, b.pix, (size_t)a.w * a.h) == 0, "pure: same input, same bitmap");
    CHECK(outline_rasterize(f, 'g', 48, 0.5f, 0, &c, err, 256) == OUTLINE_OK && fabs(ink(&c) - ink(&a)) < 0.01 * ink(&a) &&
          (c.w != a.w || memcmp(a.pix, c.pix, (size_t)a.w * a.h) != 0), "subpixel x shift keeps the ink and changes pixels");
    CHECK(outline_rasterize(f, 'g', 48, 0, 0.25f, &d, err, 256) == OUTLINE_OK && fabs(ink(&d) - ink(&a)) < 0.01 * ink(&a), "subpixel y shift keeps the ink");
    outline_bitmap_free(&a); outline_bitmap_free(&b); outline_bitmap_free(&c); outline_bitmap_free(&d);
    /* glyph scales with the size */
    outline_rasterize(f, 'o', 20, 0, 0, &a, err, 256);
    outline_rasterize(f, 'o', 40, 0, 0, &b, err, 256);
    CHECK(fabs(ink(&b) / ink(&a) - 4.0) < 0.25, "ink of o scales with the square of the size");
    outline_bitmap_free(&a); outline_bitmap_free(&b);
    /* composite glyph: accent sits above the plain e */
    outline_rasterize(f, 'e', 100, 0, 0, &a, err, 256);
    outline_rasterize(f, 0xE9, 100, 0, 0, &b, err, 256);
    CHECK(b.top > a.top + 10 && b.w >= a.w, "composite eacute: accent above e");
    outline_bitmap_free(&a); outline_bitmap_free(&b);
    /* the same glyph at very small and fairly large sizes */
    CHECK(outline_rasterize(f, 'A', 1.0f, 0, 0, &a, err, 256) == OUTLINE_OK && a.w >= 1 && a.w <= 3 && ink(&a) > 0.1, "A at 1 px is a few grey pixels");
    outline_bitmap_free(&a);
    CHECK(outline_rasterize(f, 'A', 1500, 0, 0, &a, err, 256) == OUTLINE_OK && a.h > 1000, "A at 1500 px");
    outline_bitmap_free(&a);
    /* bad sizes */
    CHECK(outline_rasterize(f, 'A', 0, 0, 0, &a, err, 256) == OUTLINE_ERROR && a.pix == NULL, "size 0 is an error");
    CHECK(outline_rasterize(f, 'A', -3, 0, 0, &a, err, 256) == OUTLINE_ERROR, "negative size is an error");
    CHECK(outline_rasterize(f, 'A', NAN, 0, 0, &a, err, 256) == OUTLINE_ERROR, "NaN size is an error");
    CHECK(outline_rasterize(f, 'A', 100, NAN, 0, &a, err, 256) == OUTLINE_ERROR, "NaN offset is an error");
    CHECK(outline_rasterize(f, 'A', 100000, 0, 0, &a, err, 256) == OUTLINE_ERROR && err[0], "size 100000 is an error with a message");
    CHECK(outline_rasterize(f, 'A', 8192, 0, 0, &a, err, 256) == OUTLINE_ERROR, "A at 8192 px exceeds the bitmap limit: error, no crash");
    CHECK(outline_rasterize(f, 0x4E00, 50, 0, 0, &a, err, 256) == OUTLINE_MISSING && a.pix == NULL && a.w == 0, "missing code point: OUTLINE_MISSING, zeroed bitmap");
    CHECK(outline_rasterize_glyph(f, 0, 50, 0, 0, &a, err, 256) == OUTLINE_OK && a.w > 0, ".notdef glyph (0) rasterises");
    outline_bitmap_free(&a);
    CHECK(outline_rasterize_glyph(f, 9999, 50, 0, 0, &a, err, 256) == OUTLINE_ERROR, "glyph index out of range is an error");
    CHECK(outline_rasterize(NULL, 'A', 50, 0, 0, &a, err, 256) == OUTLINE_MISSING, "NULL font is harmless");
    CHECK(outline_advance(f, -1) == 0 && outline_advance(f, 100000) == 0 && outline_advance(NULL, 0) == 0, "advance of bad glyphs is 0");
    outline_bitmap_free(NULL);
    outline_close(NULL);
    outline_close(f);
}

