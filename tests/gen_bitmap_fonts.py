def make_bdf():
    out = ["STARTFONT 2.1", "FONT -pxfe-Tiny-Medium-R-Normal--9-90-75-75-C-50-microsoft-cp437", "SIZE 9 75 75",
           "FONTBOUNDINGBOX 5 9 0 -2", "STARTPROPERTIES 7", "FONT_ASCENT 7", "FONT_DESCENT 2",
           'FAMILY_NAME "Tiny"', 'WEIGHT_NAME "Medium"', 'CHARSET_REGISTRY "microsoft"',
           'CHARSET_ENCODING "437"', 'COPYRIGHT "CC0"', "ENDPROPERTIES", "CHARS 6"]
    glyphs = [(65, "A", A, 0, 0, 6), (66, "B", B, 0, 0, 6), (39, "quoteright", APOS, 1, 4, 4),
              (112, "p", P, 0, -2, 5), (130, "eacute", E, 1, 0, 5), (-1, "unencoded", ["#"], 0, 0, None)]
    for code, name, rows, x, y, adv in glyphs:
        out += [f"STARTCHAR {name}", f"ENCODING {code}", "SWIDTH 600 0"]
        if adv is not None:
            out.append(f"DWIDTH {adv} 0")
        out.append(f"BBX {len(rows[0])} {len(rows)} {x} {y}")
        out.append("BITMAP")
        out += [bits_row(r, (len(r) + 7) // 8).hex().upper() for r in rows]
        out.append("ENDCHAR")
    out.append("ENDFONT")
    w("font.bdf", ("\n".join(out) + "\n").encode("latin-1"))


# ---------------------------------------------------------------------------------------------------- PCF
def make_pcf(fmt_bits, compressed, registry, encoding, codes, accel=True, names=True):
    """fmt_bits: the format word without the compressed-metrics flag (bits 0-1 glyph pad, bit 2 byte order MSB,
    bit 3 bit order MSB, bits 4-5 scan unit); codes: {code: glyph key}; the last glyph is unencoded."""
    keys = list(G) + ["x"]
    shapes = dict(G)
    shapes["x"] = ("unenc", ["##", "#."], 0, 0, 3)
    be = bool(fmt_bits & 4)
    msb_bits = bool(fmt_bits & 8)
    pad = 1 << (fmt_bits & 3)
    unit = 1 << (fmt_bits >> 4 & 3)
    order = ">" if be else "<"

    def U(code, *v):
        return struct.pack(order + code, *v)

    def table(fmt, body):
        return struct.pack("<I", fmt) + body

    strings = b""

    def add_str(s):
        nonlocal strings
        at = len(strings)
        strings += s.encode() + b"\0"
        return at

    entries = [("FONT_ASCENT", False, ASCENT), ("FONT_DESCENT", False, DESCENT), ("FAMILY_NAME", True, "Tiny"),
               ("WEIGHT_NAME", True, "Bold"), ("CHARSET_REGISTRY", True, registry), ("CHARSET_ENCODING", True, encoding)]
    body = U("i", len(entries))
    for name, is_str, val in entries:
        body += U("i", add_str(name)) + U("b", 1 if is_str else 0) + U("i", add_str(val) if is_str else val)
    body += b"\0" * ((4 - len(entries) % 4) % 4) + U("i", len(strings)) + strings
    t_props = table(fmt_bits, body)

    mets = []
    for k in keys:
        _, rows, x, y, adv = shapes[k]
        mets.append((x, x + len(rows[0]), adv, y + len(rows), -y))
    if compressed:
        body = U("H", len(mets)) + b"".join(bytes(v + 0x80 for v in m) for m in mets)
        t_metrics = table(fmt_bits | 0x100, body)
    else:
        body = U("i", len(mets)) + b"".join(U("hhhhhH", *m, 0) for m in mets)
        t_metrics = table(fmt_bits, body)

    chunks, offsets, pos = [], [], 0
    for k in keys:
        rows = shapes[k][1]
        stride = ((len(rows[0]) + 8 * pad - 1) // (8 * pad)) * pad
        offsets.append(pos)
        data = b"".join(bits_row(r, stride) for r in rows)
        chunks.append(data)
        pos += len(data)
    bits = bytearray(b"".join(chunks))
    bits += b"\0" * ((-len(bits)) % max(unit, 4))
    if be != msb_bits and unit > 1:
        bits = bytearray(b"".join(bytes(bits[i:i + unit])[::-1] for i in range(0, len(bits), unit)))
    if not msb_bits:
        bits = bytearray(int(f"{b:08b}"[::-1], 2) for b in bits)
    sizes = [len(bits)] * 4
    body = U("i", len(keys)) + b"".join(U("i", o) for o in offsets) + b"".join(U("i", s) for s in sizes) + bytes(bits)
    t_bitmaps = table(fmt_bits, body)

    cs = sorted(codes)
    first_col, last_col = min(c & 255 for c in cs), max(c & 255 for c in cs)
    first_row, last_row = min(c >> 8 for c in cs), max(c >> 8 for c in cs)
    cols = last_col - first_col + 1
    idx = [0xFFFF] * (cols * (last_row - first_row + 1))
    for c, k in codes.items():
        idx[((c >> 8) - first_row) * cols + (c & 255) - first_col] = keys.index(k)
    body = U("hhhhh", first_col, last_col, first_row, last_row, 0) + b"".join(U("H", i) for i in idx)
    t_enc = table(fmt_bits, body)

    tables = [(1, t_props), (4, t_metrics), (8, t_bitmaps), (32, t_enc)]
    if accel:
        acc = bytes(8) + U("ii", ASCENT, DESCENT) + bytes(20)
        tables.insert(1, (2, table(fmt_bits, acc)))
    if names:
        nstr, noff = b"", []
        for k in keys:
            noff.append(len(nstr))
            nstr += shapes[k][0].encode() + b"\0"
        body = U("i", len(keys)) + b"".join(U("i", o) for o in noff) + U("i", len(nstr)) + nstr
        tables.append((128, table(fmt_bits, body)))
    head = b"\x01fcp" + struct.pack("<I", len(tables))
    pos = 8 + 16 * len(tables)
    toc, blob = b"", b""
    for kind, t in tables:
        fmt = struct.unpack("<I", t[:4])[0]
        toc += struct.pack("<IIII", kind, fmt, len(t), pos + len(blob))
        blob += t + b"\0" * ((-len(t)) % 4)
    return head + toc + blob


