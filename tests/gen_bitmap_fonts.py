def codepages():
    print("/* generated by tests/gen_bitmap_fonts.py --codepages: Unicode of the bytes 0x80..0xFF, 0 = undefined in the code page.")
    print("   Bytes 0x00..0x7F are ASCII in all of them.  Names are normalised: lower case, no '-' or '_'. */")
    print("typedef struct { const char *name; uint16_t t[128]; } BmCodepage;")
    print("static const BmCodepage BM_CODEPAGES[] = {")
    for c in CODECS:
        vals = []
        for b in range(0x80, 0x100):
            try:
                vals.append(ord(bytes([b]).decode(c)))
            except UnicodeDecodeError:
                vals.append(0)
        for b in range(0x80):
            assert bytes([b]).decode(c) == chr(b), (c, b)
        rows = ["    " + ",".join(f"0x{v:04X}" for v in vals[i:i + 8]) for i in range(0, 128, 8)]
        print('  {"%s", {\n' % c.replace("-", "") + ",\n".join(rows) + "\n  }},")
    print("};")


# ---------------------------------------------------------------------------------------------------- helpers
def w(name, data):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "wb") as f:
        f.write(data)
    print(f"wrote {name} ({len(data)} bytes)")


def bits_row(row, nbytes):
    """A row of '#'/'.' as `nbytes` bytes, the leftmost pixel the most significant bit."""
    v = 0
    for i in range(nbytes * 8):
        v = v << 1 | (1 if i < len(row) and row[i] == "#" else 0)
    return v.to_bytes(nbytes, "big")


