# ---------------------------------------------------------------------------------------------------- FNT / FON
def make_fnt(version, charset, height, ascent, pix_width, first, glyphs, face):
    """glyphs: one per code from `first`: (width, rows) or None (width 0: no image)."""
    last = first + len(glyphs) - 1
    table = 148 if version == 0x300 else 118
    step = 6 if version == 0x300 else 4
    pos = table + step * (len(glyphs) + 1)
    bitmaps, entries = b"", []
    for g in glyphs:
        if g is None:
            entries.append((0, 0))
            continue
        wd, rows = g
        entries.append((wd, pos + len(bitmaps)))
        for c in range((wd + 7) // 8):
            for y in range(height):
                row = rows[y] if y < len(rows) else ""
                bits = 0
                for bit in range(8):
                    x = c * 8 + bit
                    if x < wd and x < len(row) and row[x] == "#":
                        bits |= 0x80 >> bit
                bitmaps += bytes([bits])
    face_at = pos + len(bitmaps)
    t = b""
    for wd, off in entries + [(0, 0)]:
        t += struct.pack("<HI", wd, off) if version == 0x300 else struct.pack("<HH", wd, off)
    hdr = struct.pack("<HI", version, 0) + b"CC0 test font".ljust(60, b"\0")
    hdr += struct.pack("<HHHHHHHBBBHBHHBHHBBBBHII", 0, 8, 96, 96, ascent, 1, 0, 0, 0, 0, 400, charset,
                       pix_width, height, 0 if pix_width else 1, 5, 6, first, last, 0, 0, 0, 0, face_at)
    data = hdr.ljust(table, b"\0") + t + bitmaps + face.encode() + b"\0"
    return data[:2] + struct.pack("<I", len(data)) + data[6:]


